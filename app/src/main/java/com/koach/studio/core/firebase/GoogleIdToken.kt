package com.koach.studio.core.firebase

import android.content.Context
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.NoCredentialException
import com.google.android.libraries.identity.googleid.GetGoogleIdOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential

/**
 * Asks Android Credential Manager for a Google account and returns its ID token,
 * which [FirebaseAuthRepository.signInWithGoogle] exchanges for a Firebase credential.
 *
 * The OAuth Web client ID (`default_web_client_id`) is generated by the
 * google-services plugin only once Google sign-in is enabled in the Firebase
 * console and the app's SHA fingerprints are registered, so it's looked up at
 * run time: until then this fails with a clear message instead of breaking the build.
 */
object GoogleIdToken {

    suspend fun request(context: Context): Result<String> = runCatching {
        val webClientId = webClientId(context)
            ?: throw IllegalStateException("Google sign-in isn't set up for this build yet. Use email, or ask the studio to enable it.")
        val option = GetGoogleIdOption.Builder()
            .setServerClientId(webClientId)
            .setFilterByAuthorizedAccounts(false)
            .setAutoSelectEnabled(false)
            .build()
        val request = GetCredentialRequest.Builder().addCredentialOption(option).build()
        val credential = try {
            CredentialManager.create(context).getCredential(context, request).credential
        } catch (e: GetCredentialCancellationException) {
            throw IllegalStateException("Google sign-in was cancelled.")
        } catch (e: NoCredentialException) {
            throw IllegalStateException("No Google account is available on this device.")
        }
        if (credential is CustomCredential && credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
            GoogleIdTokenCredential.createFrom(credential.data).idToken
        } else {
            throw IllegalStateException("Google didn't return an account. Please try again.")
        }
    }

    private fun webClientId(context: Context): String? {
        val id = context.resources.getIdentifier("default_web_client_id", "string", context.packageName)
        return if (id == 0) null else context.getString(id).takeIf { it.isNotBlank() }
    }
}
